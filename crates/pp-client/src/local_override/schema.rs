// Custom rule set (user-defined)
// ---------------------------------------------------------------------------

/// Rule set file format (aligned with sing-box rule_set `format` values).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum RuleSetFormat {
    /// JSON source (`format: "source"`).
    Source,
    /// sing-box binary `.srs` (`format: "binary"`).
    Binary,
}

/// Where a custom rule set's content comes from.
///
/// Serialized internally-tagged (`"kind": "remote" | "manual"`) so the stored
/// `local_override.json` and the shell View/Input contract share one shape.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum CustomRuleSetSource {
    /// Remote URL; content is downloaded and cached as a local file
    /// (`<data_dir>/rulesets/custom/<id>.srs|.json`) and injected as a local
    /// rule_set.
    Remote { url: String, format: RuleSetFormat },
    /// Manual sing-box rule_set source JSON pasted by the user; persisted to
    /// `<data_dir>/rulesets/custom/<id>.json` and injected as a local rule_set
    /// (`format: "source"`).
    Manual { content: String },
}

/// A user-defined rule set entry (remote URL / manual JSON).
///
/// 规则集是**纯资源**：不再有 `enabled` 概念（旧文件的 `enabled` 字段在
/// 反序列化时被 serde 静默忽略）。是否被使用只由引用它的规则决定——注入时
/// 仅注入「被注入规则引用 && backing 文件已存在」的规则集。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CustomRuleSet {
    /// Unique rule set ID (UUID v4 generated by frontend).
    pub id: String,
    /// Display name (user-visible).
    #[serde(default)]
    pub name: String,
    /// Tag used in core config rule_set references; must not collide with
    /// built-in `community_id`s or other custom tags.
    pub tag: String,
    /// Content source.
    pub source: CustomRuleSetSource,
    /// Last successful update timestamp (Remote only; 0 until first success).
    ///
    /// 语义为**本地缓存写入时间**（下载完成时刻）。
    #[serde(default)]
    pub last_updated: u64,
    /// Remote source's latest modification time (Remote only; 0 = unknown).
    ///
    /// 取自远端 `Last-Modified` 响应头（Unix 秒）；`remote_updated_at >
    /// last_updated` 即表示远端已有新版本（前端据此显示「有更新」标记）。
    /// 无该响应头时保持 0。旧版文件无此字段时 serde 默认 0。
    #[serde(default)]
    pub remote_updated_at: u64,
}

impl CustomRuleSet {
    /// Expected `RuleSetFormat` of this rule set's backing file.
    pub fn file_format(&self) -> RuleSetFormat {
        match self.source {
            CustomRuleSetSource::Remote { format, .. } => format,
            CustomRuleSetSource::Manual { .. } => RuleSetFormat::Source,
        }
    }
}

