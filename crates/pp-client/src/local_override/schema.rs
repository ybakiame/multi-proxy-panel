/// Rule set reference (locally downloaded or remote subscription).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LocalRuleSetRef {
    pub id: String,
    /// Display name (user-visible).
    pub name: String,
    /// Tag used in core config references.
    pub tag: String,
    /// Rule set type.
    pub kind: RuleSetKind,
    /// Local file path (downloaded cache) or remote URL.
    pub source: RuleSetSource,
    /// Whether enabled.
    #[serde(default = "default_true")]
    pub enabled: bool,
    /// Auto-update interval in minutes (0 = no auto-update).
    #[serde(default)]
    pub auto_update_interval_minutes: u32,
    /// Last update timestamp.
    #[serde(default)]
    pub last_updated: u64,
}

/// Rule set kind.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleSetKind {
    /// sing-box: `remote` rule_set (binary .srs).
    SingBoxRemote,
    /// sing-box: `local` rule_set (source .json).
    SingBoxLocal,
}

/// Rule set source.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleSetSource {
    /// Remote URL (needs download cache).
    Remote { url: String },
    /// Local file path (already downloaded).
    Local { path: String },
    /// Built-in bundled resource (shipped with app).
    Bundled { name: String },
}

