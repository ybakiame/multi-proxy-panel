/// V2Ray transport settings (curated fields).
///
/// `kind` is the sing-box transport `type` (`tcp` / `ws` / `grpc` / `http` /
/// `quic` / `httpupgrade`). `path` maps to `path` (or `service_name` for gRPC)
/// and `host` to the transport's host / Host header.
