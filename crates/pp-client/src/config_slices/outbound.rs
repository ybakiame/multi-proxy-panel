//! Custom outbound slice schema (ADR-0005 §3.1).
//!
//! Each protocol struct only carries curated high-value fields; everything else
//! stays available through the YAML/JS override escape hatch (ADR-0005 D2).
//! Rendering lives in [`crate::config_slices::render_outbound`].

use serde::{Deserialize, Serialize};

use super::default_true;

/// Forced prefix for every slice-managed outbound tag (ADR-0005 §3.1).
pub const OUTBOUND_TAG_PREFIX: &str = "slice-";

/// Custom outbound slice.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct OutboundsSlice {
    /// Slice master switch; `false` never injects custom outbounds.
    #[serde(default)]
    pub enabled: bool,
    /// User-defined outbounds.
    #[serde(default)]
    pub items: Vec<CustomOutbound>,
}

/// A single custom outbound. `protocol` is a tagged enum flattened into the
/// object, so the stored JSON is `{ id, name, enabled, type, …protocol fields }`.
///
/// Every field is `#[serde(default)]` except the flattened `protocol`, whose
/// `type` discriminator is inherently required; an item without a known `type`
/// makes the file fail to parse, so [`crate::config_slices::ConfigSlicesStore::load`]
/// falls back to the default (empty) slice set.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CustomOutbound {
    /// Unique ID (UUID v4 generated by the frontend).
    #[serde(default)]
    pub id: String,
    /// Display name; also the source of the generated `slice-` tag.
    #[serde(default)]
    pub name: String,
    /// Whether the outbound is injected.
    #[serde(default = "default_true")]
    pub enabled: bool,
    /// Protocol-specific fields (structured enum, tagged by `type`).
    #[serde(flatten)]
    pub protocol: OutboundProtocol,
}

impl CustomOutbound {
    /// Resolved sing-box outbound tag (`slice-` + slug of [`Self::name`]).
    #[must_use]
    pub fn tag(&self) -> String {
        outbound_tag(&self.name)
    }
}

/// Protocol-specific outbound payload.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum OutboundProtocol {
    Vless(VlessOutbound),
    Vmess(VmessOutbound),
    Shadowsocks(ShadowsocksOutbound),
    Trojan(TrojanOutbound),
    Hysteria2(Hysteria2Outbound),
}

impl OutboundProtocol {
    /// Server address of the protocol payload.
    #[must_use]
    pub fn server(&self) -> &str {
        match self {
            Self::Vless(o) => &o.server,
            Self::Vmess(o) => &o.server,
            Self::Shadowsocks(o) => &o.server,
            Self::Trojan(o) => &o.server,
            Self::Hysteria2(o) => &o.server,
        }
    }

    /// Server port of the protocol payload.
    #[must_use]
    pub fn server_port(&self) -> u16 {
        match self {
            Self::Vless(o) => o.server_port,
            Self::Vmess(o) => o.server_port,
            Self::Shadowsocks(o) => o.server_port,
            Self::Trojan(o) => o.server_port,
            Self::Hysteria2(o) => o.server_port,
        }
    }
}

