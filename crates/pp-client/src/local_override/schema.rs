/// A single local rule (translated to sing-box route rule fields).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LocalRule {
    /// Unique rule ID (UUID v4 generated by frontend).
    pub id: String,
    /// User-defined name (optional, auto-generated summary when empty).
    #[serde(default)]
    pub name: String,
    /// Whether the rule is enabled.
    #[serde(default = "default_true")]
    pub enabled: bool,
    /// Rule match type.
    pub match_type: RuleMatchType,
    /// Match target (semantics vary by match_type).
    pub target: String,
    /// Routing action.
    pub action: RuleAction,
    /// Advanced options.
    #[serde(default)]
    pub advanced: RuleAdvancedOptions,
    /// User note.
    #[serde(default)]
    pub note: String,
    /// Creation timestamp (for sort stability).
    pub created_at: u64,
    /// Sort weight (smaller = earlier).
    pub sort_order: i32,
}

/// Rule match type (aligned with sing-box route rule fields).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleMatchType {
    /// Exact domain match (sing-box: `domain`).
    Domain,
    /// Domain suffix match (sing-box: `domain_suffix`).
    DomainSuffix,
    /// Domain keyword match (sing-box: `domain_keyword`).
    DomainKeyword,
    /// IP CIDR (sing-box: `ip_cidr`).
    IpCidr,
    /// Source IP CIDR (sing-box: `source_ip_cidr`).
    SourceIpCidr,
    /// Rule set reference (sing-box: `rule_set`).
    RuleSet,
    /// Android app package name (sing-box: `package_name`).
    #[cfg(target_os = "android")]
    AppPackage,
    /// Process name (desktop, sing-box: `process_name`).
    #[cfg(not(target_os = "android"))]
    ProcessName,
    /// Port range (sing-box: `port`).
    Port,
    /// Final catch-all rule (sing-box: `final` in route.final).
    ///
    /// Note: Final rule in the list is only a placeholder; actual write goes to
    /// route.final in core config.
    Final,
}

/// Routing action.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleAction {
    /// Route to main selector / proxy group.
    Proxy,
    /// Direct connection.
    Direct,
    /// Reject.
    Reject,
    /// Route to specific outbound tag (advanced, target existence should be validated).
    Outbound { tag: String },
}

impl RuleAction {
    /// Returns the outbound tag string for core config generation.
    pub fn outbound_tag(&self) -> &str {
        match self {
            RuleAction::Proxy => "proxy",
            RuleAction::Direct => "direct",
            RuleAction::Reject => "reject",
            RuleAction::Outbound { tag } => tag.as_str(),
        }
    }
}

/// Advanced options for rules.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct RuleAdvancedOptions {
    /// Skip DNS resolution (only valid for domain-type rules).
    ///
    /// sing-box: no direct field, split `domain` + `ip_cidr` for semantics.
    #[serde(default)]
    pub no_resolve: bool,
    /// Invert match.
    ///
    /// sing-box: `invert: true`.
    #[serde(default)]
    pub invert: bool,
    /// Protocol sniff (sing-box 1.12+ action: sniff, not exposed to users yet).
    #[serde(skip)]
    pub _sniff: bool,
}

