/**
 * Build the forced `slice-` tag from a display name (mirrors Rust
 * `outbound_tag`, ADR-0005 §3.1).
 *
 * The name is lower-cased and slugified: unicode alphanumerics are kept, every
 * run of other characters becomes a single `-`, leading/trailing `-` are
 * trimmed. An empty result falls back to `slice-outbound`.
 */
export function outboundTag(name: string): string {
  let slug = "";
  let pendingDash = false;
  for (const ch of name.trim()) {
    if (/[\p{L}\p{N}]/u.test(ch)) {
      if (pendingDash && slug.length > 0) {
        slug += "-";
      }
      pendingDash = false;
      slug += ch.toLowerCase();
    } else {
      pendingDash = true;
    }
  }
  return slug.length === 0 ? "slice-outbound" : `slice-${slug}`;
}

/** Default (all slices disabled) config slices, mirroring Rust `ConfigSlices::default`. */
export function defaultConfigSlices(): ConfigSlices {
  return {
    version: SLICE_VERSION,
    dns: {
      enabled: false,
      mode: "follow_system",
      servers: [],
      rules: [],
      final_tag: "",
      strategy: "prefer_ipv4",
    },
    outbounds: {
      enabled: false,
      items: [],
    },
    experimental: {
      enabled: false,
      cache_file: {
        enabled: false,
        path: "",
        cache_id: "",
        store_fakeip: false,
      },
    },
  };
}
