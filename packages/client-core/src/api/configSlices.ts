/**
 * Config slices (ADR-0005 P0) API types and functions.
 *
 * Aligned with Rust `pp_client::config_slices` (`dns.rs` / `outbound.rs` /
 * `schema.rs`). The Tauri commands take/return the full [`ConfigSlices`]
 * document directly (no View/Input split): `config_slices_save` is a full-patch
 * and validates server-side before writing, so a validation failure rejects
 * without touching `data_dir/config_slices.json`.
 */

import { invoke } from "@tauri-apps/api/core";

/** Current slice schema version (mirrors Rust `SLICE_VERSION`). */
export const SLICE_VERSION = 1;

// ---------------------------------------------------------------------------
// DNS slice
// ---------------------------------------------------------------------------

/** Platform DNS mode (ADR-0005 D1). */
export type DnsMode = "follow_system" | "takeover";

/** Domain resolution strategy (maps to sing-box `strategy` / `domain_strategy`). */
export type DnsStrategy = "prefer_ipv4" | "prefer_ipv6" | "ipv4_only" | "ipv6_only";

/** DNS server type (`dns.servers[].type`). */
export type DnsServerType = "udp" | "tls" | "https" | "quic" | "h3" | "local" | "fakeip";

/** DNS rule match type (determines the sing-box match field). */
export type DnsMatchType = "domain" | "domain_suffix" | "domain_keyword" | "rule_set" | "query_type";

/** DNS rule action (`dns.rules[].action`). */
export type DnsRuleAction = "route" | "predefined" | "reject";

/** A single DNS server (curated fields). */
export interface DnsServer {
  /** Unique tag within the slice; referenced by `rules` and `final_tag`. */
  tag: string;
  /** Server address (IP or domain); unused for `local` and `fakeip`. */
  server: string;
  server_type: DnsServerType;
  /** Server port (sing-box default per type when `null`). */
  server_port: number | null;
  /**
   * FakeIP IPv4 range (`fakeip` type only); empty renders sing-box's default
   * `198.18.0.0/15`.
   *
   * Mirrors the Rust `String` + `#[serde(default)]` field: the wire form is
   * always a string (possibly empty), never `null`.
   */
  inet4_range: string;
  /** FakeIP IPv6 range (`fakeip` type only); empty omits the field. */
  inet6_range: string;
  /** Upstream outbound tag (empty = default direct dial). */
  detour: string;
  /**
   * Per-server strategy override.
   *
   * Not rendered: sing-box 1.12+ new DNS servers have no per-server query
   * strategy field. Kept for schema completeness / future use.
   */
  strategy: DnsStrategy | null;
  /** DNS server tag used to resolve this server's own domain. */
  domain_resolver: string;
}

/** A single DNS routing rule (rendered to `dns.rules[]`). */
export interface DnsRule {
  /** Unique rule ID (UUID v4 generated by the frontend). */
  id: string;
  enabled: boolean;
  match_type: DnsMatchType;
  /**
   * Match target (semantics depend on `match_type`).
   *
   * For `query_type` this is a comma-separated list (e.g. `A,AAAA`).
   */
  target: string;
  /** Target DNS server tag (`action: "route"`). */
  server_tag: string;
  /** Rule action (`route` default; `predefined` / `reject`). */
  action: DnsRuleAction;
  /** Response code for `predefined` (empty = `NOERROR`). */
  rcode: string;
}

/** DNS slice: structured form of the sing-box top-level `dns` object. */
export interface DnsSlice {
  /** Slice master switch; `false` never injects the DNS slice. */
  enabled: boolean;
  /** Platform DNS mode (only Android diverges; desktop always behaves as takeover). */
  mode: DnsMode;
  servers: DnsServer[];
  rules: DnsRule[];
  /** Default server tag (sing-box `dns.final`); required when takeover is on. */
  final_tag: string;
  /** Default domain strategy (sing-box `dns.strategy`). */
  strategy: DnsStrategy;
}

// ---------------------------------------------------------------------------
// Custom outbound slice
// ---------------------------------------------------------------------------

/** Outbound TLS settings (curated fields). */
export interface OutboundTls {
  enabled: boolean;
  server_name: string;
  insecure: boolean;
  alpn: string[];
}

/**
 * V2Ray transport settings (curated fields).
 *
 * `kind` is the sing-box transport `type` (`tcp` / `ws` / `grpc` / `http` /
 * `quic` / `httpupgrade`). `path` maps to `path` (or `service_name` for gRPC)
 * and `host` to the transport's host / Host header.
 */
export interface OutboundTransport {
  kind: string;
  path: string;
  host: string;
}

/** Hysteria2 QUIC traffic obfuscator. */
export interface Hysteria2Obfs {
  /** Obfuscator type (`salamander` / `gecko`; empty = disabled). */
  obfs_type: string;
  password: string;
}

/** VLESS outbound (curated fields). */
export interface VlessOutbound {
  type: "vless";
  server: string;
  server_port: number;
  uuid: string;
  /** VLESS sub-protocol, e.g. `xtls-rprx-vision` (empty = none). */
  flow: string;
  tls: OutboundTls;
  transport: OutboundTransport;
}

/** VMess outbound (curated fields). */
export interface VmessOutbound {
  type: "vmess";
  server: string;
  server_port: number;
  uuid: string;
  /** Encryption method (`auto` / `none` / `aes-128-gcm` / `chacha20-poly1305`, …). */
  security: string;
  /** Alter ID (`0` = AEAD). */
  alter_id: number;
  tls: OutboundTls;
  transport: OutboundTransport;
}

/** Shadowsocks outbound (curated fields). */
export interface ShadowsocksOutbound {
  type: "shadowsocks";
  server: string;
  server_port: number;
  method: string;
  password: string;
}

/** Trojan outbound (curated fields). */
export interface TrojanOutbound {
  type: "trojan";
  server: string;
  server_port: number;
  password: string;
  tls: OutboundTls;
  transport: OutboundTransport;
}

/** Hysteria2 outbound (curated fields). */
export interface Hysteria2Outbound {
  type: "hysteria2";
  server: string;
  server_port: number;
  password: string;
  /** Max upload bandwidth in Mbps (0 = BBR congestion control). */
  up_mbps: number;
  /** Max download bandwidth in Mbps (0 = BBR congestion control). */
  down_mbps: number;
  obfs: Hysteria2Obfs;
  tls: OutboundTls;
}

/**
 * Selector outbound: manually picks one member outbound (Clash API controlled).
 *
 * Fields mirror Rust `SelectorOutbound` (sing-box 1.14 `outbound/selector`).
 */
export interface SelectorOutbound {
  type: "selector";
  /** Member outbound tags to select from (required, must not be empty). */
  outbounds: string[];
  /** Default member tag; the first member is used when empty. */
  default: string;
  /** Interrupt existing connections when the selection changes. */
  interrupt_exist_connections: boolean;
}

/**
 * URLTest outbound: automatically picks the lowest-latency member.
 *
 * Fields mirror Rust `UrlTestOutbound` (sing-box 1.14 `outbound/urltest`). The
 * type discriminator is `urltest` (no underscore) to match the Rust explicit
 * `#[serde(rename = "urltest")]`.
 */
export interface UrlTestOutbound {
  type: "urltest";
  /** Member outbound tags to test (required, must not be empty). */
  outbounds: string[];
  /** Test URL (empty = sing-box default `https://www.gstatic.com/generate_204`). */
  url: string;
  /** Test interval as a duration string (e.g. `3m`; empty = sing-box default). */
  interval: string;
  /** Test tolerance in milliseconds (`0` = sing-box default). */
  tolerance: number;
  /** Interrupt existing connections when the selected outbound changes. */
  interrupt_exist_connections: boolean;
}

/**
 * Protocol-specific outbound payload.
 *
 * Mirrors the Rust internally-tagged enum (`tag = "type"`): the discriminant is
 * flattened onto the containing `CustomOutbound`, so it sits next to
 * `id` / `name` / `enabled` and the protocol fields.
 */
export type OutboundProtocol =
  | VlessOutbound
  | VmessOutbound
  | ShadowsocksOutbound
  | TrojanOutbound
  | Hysteria2Outbound
  | SelectorOutbound
  | UrlTestOutbound;

/** Group outbound payloads (selector / urltest) — never concrete proxy nodes. */
export type GroupOutbound = SelectorOutbound | UrlTestOutbound;

/**
 * Type predicate for group outbounds (selector / urltest).
 *
 * Mirrors Rust `OutboundProtocol::is_group`; used to separate the list into
 * 「分组」/「节点」 sections and to keep group fields out of node forms.
 */
export function isGroupOutbound(protocol: OutboundProtocol): protocol is GroupOutbound {
  return protocol.type === "selector" || protocol.type === "urltest";
}

/**
 * A single custom outbound (`{ id, name, enabled, type, …protocol fields }`).
 *
 * `OutboundProtocol` is flattened into this object in the Rust wire format;
 * the intersection keeps the union discriminated by `type`.
 */
export type CustomOutbound = {
  /** Unique ID (UUID v4 generated by the frontend). */
  id: string;
  /** Display name; also the source of the generated `slice-` tag. */
  name: string;
  enabled: boolean;
} & OutboundProtocol;

/** Custom outbound slice. */
export interface OutboundsSlice {
  /** Slice master switch; `false` never injects custom outbounds. */
  enabled: boolean;
  items: CustomOutbound[];
}

