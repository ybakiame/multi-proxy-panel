//! Local Override schema types (ADR-0002, section 3.1.1).
//!
//! Dual-core unified abstraction for client-side rule management.

use serde::{Deserialize, Serialize};

// ---------------------------------------------------------------------------
// Top-level container
// ---------------------------------------------------------------------------

/// Local Override container, isolated by core type.
///
/// Stored at `data_dir/local_override.json`.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct LocalOverride {
    /// sing-box side local rules and rule sets.
    #[serde(default)]
    pub singbox: CoreLocalOverride,
    /// mihomo side local rules and rule sets.
    #[serde(default)]
    pub mihomo: CoreLocalOverride,
    /// Rule set subscription list (core-agnostic).
    #[serde(default)]
    pub rule_set_subscriptions: Vec<RuleSetSubscription>,
    /// Applied template records (for display / revert).
    #[serde(default)]
    pub applied_templates: Vec<AppliedTemplate>,
}

// ---------------------------------------------------------------------------
// Per-core override
// ---------------------------------------------------------------------------

/// Per-core local override.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CoreLocalOverride {
    /// User-defined rule cards (ordered).
    #[serde(default)]
    pub rules: Vec<LocalRule>,
    /// Rule set reference list (ordered, maps to rule_sets / rule-providers).
    #[serde(default)]
    pub rule_sets: Vec<LocalRuleSetRef>,
    /// Master switch for local override.
    #[serde(default = "default_true")]
    pub enabled: bool,
}

impl Default for CoreLocalOverride {
    fn default() -> Self {
        Self {
            rules: Vec::new(),
            rule_sets: Vec::new(),
            enabled: true,
        }
    }
}

// ---------------------------------------------------------------------------
// Local rule card
// ---------------------------------------------------------------------------

/// A single local rule (dual-core unified abstraction, translated per core).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LocalRule {
    /// Unique rule ID (UUID v4 generated by frontend).
    pub id: String,
    /// User-defined name (optional, auto-generated summary when empty).
    #[serde(default)]
    pub name: String,
    /// Whether the rule is enabled.
    #[serde(default = "default_true")]
    pub enabled: bool,
    /// Rule match type.
    pub match_type: RuleMatchType,
    /// Match target (semantics vary by match_type).
    pub target: String,
    /// Routing action.
    pub action: RuleAction,
    /// Advanced options.
    #[serde(default)]
    pub advanced: RuleAdvancedOptions,
    /// User note.
    #[serde(default)]
    pub note: String,
    /// Creation timestamp (for sort stability).
    pub created_at: u64,
    /// Sort weight (smaller = earlier).
    pub sort_order: i32,
}

/// Rule match type (aligned with sing-box route rule fields, translated for mihomo).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleMatchType {
    /// Exact domain match (sing-box: `domain` / mihomo: `DOMAIN`).
    Domain,
    /// Domain suffix match (sing-box: `domain_suffix` / mihomo: `DOMAIN-SUFFIX`).
    DomainSuffix,
    /// Domain keyword match (sing-box: `domain_keyword` / mihomo: `DOMAIN-KEYWORD`).
    DomainKeyword,
    /// IP CIDR (sing-box: `ip_cidr` / mihomo: `IP-CIDR` / `IP-CIDR6`).
    IpCidr,
    /// Source IP CIDR (sing-box: `source_ip_cidr` / mihomo: `SRC-IP-CIDR`).
    SourceIpCidr,
    /// Rule set reference (sing-box: `rule_set` / mihomo: `RULE-SET`).
    RuleSet,
    /// Android app package name (sing-box: `package_name` / mihomo: `PROCESS-NAME` approx).
    #[cfg(target_os = "android")]
    AppPackage,
    /// Process name (desktop, sing-box: `process_name` / mihomo: `PROCESS-NAME`).
    #[cfg(not(target_os = "android"))]
    ProcessName,
    /// Port range (sing-box: `port` / mihomo: `DST-PORT`).
    Port,
    /// Final catch-all rule (sing-box: `final` in route.final / mihomo: `MATCH`).
    ///
    /// Note: Final rule in the list is only a placeholder; actual write goes to
    /// route.final / MATCH in core config.
    Final,
}

/// Routing action.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleAction {
    /// Route to main selector / proxy group.
    Proxy,
    /// Direct connection.
    Direct,
    /// Reject.
    Reject,
    /// Route to specific outbound tag (advanced, target existence should be validated).
    Outbound { tag: String },
}

impl RuleAction {
    /// Returns the outbound tag string for core config generation.
    pub fn outbound_tag(&self) -> &str {
        match self {
            RuleAction::Proxy => "proxy",
            RuleAction::Direct => "direct",
            RuleAction::Reject => "reject",
            RuleAction::Outbound { tag } => tag.as_str(),
        }
    }
}

/// Advanced options for rules.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct RuleAdvancedOptions {
    /// Skip DNS resolution (only valid for domain-type rules).
    ///
    /// sing-box: no direct field, split `domain` + `ip_cidr` for semantics.
    /// mihomo: `no-resolve` flag.
    #[serde(default)]
    pub no_resolve: bool,
    /// Invert match.
    ///
    /// sing-box: `invert: true` / mihomo: simulated via logical rule `NOT`.
    #[serde(default)]
    pub invert: bool,
    /// Protocol sniff (sing-box 1.12+ action: sniff, not exposed to users yet).
    #[serde(skip)]
    pub _sniff: bool,
}

// ---------------------------------------------------------------------------
// Rule set reference
