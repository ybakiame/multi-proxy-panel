/// Rule set reference (locally downloaded or remote subscription).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LocalRuleSetRef {
    pub id: String,
    /// Display name (user-visible).
    pub name: String,
    /// Tag used in core config references.
    pub tag: String,
    /// Rule set type.
    pub kind: RuleSetKind,
    /// Local file path (downloaded cache) or remote URL.
    pub source: RuleSetSource,
    /// Whether enabled.
    #[serde(default = "default_true")]
    pub enabled: bool,
    /// Auto-update interval in minutes (0 = no auto-update).
    #[serde(default)]
    pub auto_update_interval_minutes: u32,
    /// Last update timestamp.
    #[serde(default)]
    pub last_updated: u64,
}

/// Rule set kind (core-specific format).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleSetKind {
    /// sing-box: `remote` rule_set (binary .srs).
    SingBoxRemote,
    /// sing-box: `local` rule_set (source .json).
    SingBoxLocal,
    /// mihomo: `http` rule-provider.
    MihomoHttp,
    /// mihomo: `file` rule-provider.
    MihomoFile,
}

/// Rule set source.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleSetSource {
    /// Remote URL (needs download cache).
    Remote { url: String },
    /// Local file path (already downloaded).
    Local { path: String },
    /// Built-in bundled resource (shipped with app).
    Bundled { name: String },
}

// ---------------------------------------------------------------------------
// Rule set subscription (core-agnostic market list)
// ---------------------------------------------------------------------------

/// Rule set subscription entry (unified list, core-agnostic).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RuleSetSubscription {
    pub id: String,
    /// Community rule set identifier (e.g. `geoip-cn`, `geosite-ads`).
    pub community_id: String,
    /// Display name.
    pub display_name: String,
    /// Category tag.
    pub category: RuleSetCategory,
    /// Whether subscribed (checked).
    #[serde(default)]
    pub subscribed: bool,
    /// sing-box remote URL template (contains `{tag}` placeholder).
    pub singbox_url_template: String,
    /// mihomo remote URL template (contains `{tag}` placeholder).
    pub mihomo_url_template: String,
    /// Default auto-update interval in minutes.
    pub default_interval_minutes: u32,
}

/// Rule set category.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuleSetCategory {
    Geoip,
    Geosite,
    Ads,
    Privacy,
    Malware,
    Custom,
}

// ---------------------------------------------------------------------------
// Applied template record
// ---------------------------------------------------------------------------

/// Record of an applied scenario template.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AppliedTemplate {
    pub template_id: String,
    pub applied_at: u64,
    /// Rule IDs generated when applying (for one-click revert).
    pub generated_rule_ids: Vec<String>,
}

