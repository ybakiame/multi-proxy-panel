//! Local Override schema types (ADR-0002, section 3.1.1).
//!
//! Client-side rule management abstraction (sing-box only).

use serde::{Deserialize, Serialize};

// ---------------------------------------------------------------------------
// Top-level container
// ---------------------------------------------------------------------------

/// Local Override container.
///
/// Stored at `data_dir/local_override.json`.
///
/// 存量兼容：旧版文件中的 `mihomo` 桶字段在反序列化时被静默丢弃（serde 忽略未知字段）。
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct LocalOverride {
    /// sing-box side local rules and rule sets.
    #[serde(default)]
    pub singbox: CoreLocalOverride,
    /// Legacy built-in rule set subscription list.
    ///
    /// **Deprecated**：内置规则集订阅机制已废弃，统一为用户自控的
    /// [`CustomRuleSet`] 模型。本字段仅保留 serde 兼容以读取旧版文件
    /// （存量迁移在 [`crate::local_override::store::LocalOverrideStore::load`]
    /// 中把 `subscribed == true` 的条目转换为 custom Remote 后清空）；
    /// 写回时恒为空数组，业务代码不得再依赖它。
    #[serde(default)]
    pub rule_set_subscriptions: Vec<RuleSetSubscription>,
    /// Legacy applied scenario-template records.
    ///
    /// **Deprecated**：场景模板功能已移除（ADR-0005 后续决策：出站分组 + 规则
    /// 组合取代场景模板）。字段仅保留 serde 兼容以读取旧版
    /// `local_override.json`（历史任意形态均可解析），不再被任何逻辑读取；
    /// [`crate::local_override::store::LocalOverrideStore::load`] 会将其清空，
    /// 写回恒为空数组。
    #[serde(default)]
    pub applied_templates: Vec<serde_json::Value>,
    /// User-defined custom rule sets (remote URL download / manual source JSON).
    ///
    /// 旧版文件无此段时反序列化为空 Vec（`#[serde(default)]` 静默兼容）。
    #[serde(default)]
    pub custom_rule_sets: Vec<CustomRuleSet>,
    /// Legacy scenario-template definitions (rule ID reference lists).
    ///
    /// **Deprecated**：场景模板功能已移除，同 [`Self::applied_templates`]；
    /// 字段仅保留 serde 兼容，不再被任何逻辑读取，写回恒为空数组。
    #[serde(default)]
    pub custom_templates: Vec<serde_json::Value>,
}

// ---------------------------------------------------------------------------
// Per-core override
// ---------------------------------------------------------------------------

/// Per-core local override.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CoreLocalOverride {
    /// User-defined rule cards (ordered).
    #[serde(default)]
    pub rules: Vec<LocalRule>,
    /// Rule set reference list (ordered, maps to rule_sets).
    #[serde(default)]
    pub rule_sets: Vec<LocalRuleSetRef>,
    /// Master switch for local override.
    #[serde(default = "default_true")]
    pub enabled: bool,
}

impl Default for CoreLocalOverride {
    fn default() -> Self {
        Self {
            rules: Vec::new(),
            rule_sets: Vec::new(),
            enabled: true,
        }
    }
}

// ---------------------------------------------------------------------------
// Local rule card
